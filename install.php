    <summary>Server check <?= in_array(false, array_slice($checks, 0, 6), true) ? '<span class="pill pill-cancelled">Needs attention</span>' : '<span class="pill pill-delivered">All good</span>' ?></summary>
    <ul>
      <?php foreach ($checks as $label => $ok): ?>
