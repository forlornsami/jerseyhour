<?php
/**
 * JerseyHour — one-time installer.
 * Creates the database, your admin account and default content.
 * Delete this file after installation (the site also locks it automatically).
 */
define('INSTALLER', true);
require __DIR__ . '/includes/bootstrap.php';
require __DIR__ . '/includes/seed.php';

$installed = is_file(APP_ROOT . '/includes/config.php');
$errors = [];
$done = false;

$checks = [
    'PHP 7.4 or newer'                 => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO extension'                    => extension_loaded('pdo'),
    'SQLite or MySQL driver'           => extension_loaded('pdo_sqlite') || extension_loaded('pdo_mysql'),
    'includes/ folder is writable'     => is_writable(APP_ROOT . '/includes'),
    'data/ folder is writable'         => is_writable(APP_ROOT . '/data'),
    'uploads/ folder is writable'      => is_writable(APP_ROOT . '/uploads') && is_writable(APP_ROOT . '/uploads/products'),
    'GD image library (for resizing)'  => extension_loaded('gd'),
];
$hasSqlite = extension_loaded('pdo_sqlite');
$hasMysql = extension_loaded('pdo_mysql');

$in = [
    'store_name' => $_POST['store_name'] ?? 'JerseyHour',
    'username'   => $_POST['username'] ?? 'admin',
    'driver'     => $_POST['driver'] ?? ($hasSqlite ? 'sqlite' : 'mysql'),
    'db_host'    => $_POST['db_host'] ?? 'localhost',
    'db_name'    => $_POST['db_name'] ?? '',
    'db_user'    => $_POST['db_user'] ?? '',
    'demo'       => is_post() ? !empty($_POST['demo']) : true,
];

if (!$installed && is_post()) {
    if (!csrf_valid()) $errors[] = 'Session expired — please submit the form again.';
    $pass = (string)($_POST['password'] ?? '');
    $pass2 = (string)($_POST['password2'] ?? '');
    if (!preg_match('~^[A-Za-z0-9_.-]{3,40}$~', $in['username'])) $errors[] = 'Username must be 3–40 characters (letters, numbers, dot, dash, underscore).';
    if (strlen($pass) < 8) $errors[] = 'Password must be at least 8 characters.';
    if ($pass !== $pass2) $errors[] = 'Passwords do not match.';
    if (!in_array($in['driver'], ['sqlite', 'mysql'], true)) $errors[] = 'Choose a database type.';
    if ($in['driver'] === 'sqlite' && !$hasSqlite) $errors[] = 'SQLite is not available on this server — choose MySQL.';
    if ($in['driver'] === 'mysql' && !$hasMysql) $errors[] = 'MySQL driver is not available on this server.';
    if ($in['driver'] === 'mysql' && ($in['db_name'] === '' || $in['db_user'] === '')) $errors[] = 'Enter your MySQL database name and user.';

    if (!$errors) {
        try {
            $cfg = ['path' => '', 'host' => $in['db_host'], 'name' => $in['db_name'], 'user' => $in['db_user'], 'pass' => (string)($_POST['db_pass'] ?? '')];
            if ($in['driver'] === 'sqlite') {
                $cfg['path'] = 'data/jerseyhour-' . bin2hex(random_bytes(8)) . '.sqlite';
            }
            $pdo = db_connect($in['driver'], $cfg);

            if ($in['driver'] === 'mysql' && $pdo->query("SHOW TABLES LIKE 'products'")->fetch()) {
                throw new RuntimeException('This MySQL database already contains JerseyHour tables. Use an empty database.');
            }

            foreach (db_schema($in['driver']) as $sql) {
                $pdo->exec($sql);
            }
            $pdo->beginTransaction();
            seed_settings($pdo, ['store_name' => trim($in['store_name']) ?: 'JerseyHour']);
            seed_pages($pdo);
            $catIds = seed_categories($pdo);
            if ($in['demo']) seed_products($pdo, $catIds);
            $pdo->prepare('INSERT INTO admins (username, password_hash, created_at) VALUES (?, ?, ?)')
                ->execute([$in['username'], password_hash($pass, PASSWORD_DEFAULT), date('Y-m-d H:i:s')]);
            $pdo->commit();

            $x = fn($v) => var_export((string)$v, true);
            $config = "<?php\n// Generated by JerseyHour installer on " . date('Y-m-d H:i') . "\n"
                . "define('DB_DRIVER', " . $x($in['driver']) . ");\n"
                . "define('DB_PATH', " . $x($cfg['path']) . ");\n"
                . "define('DB_HOST', " . $x($cfg['host']) . ");\n"
                . "define('DB_NAME', " . $x($cfg['name']) . ");\n"
                . "define('DB_USER', " . $x($cfg['user']) . ");\n"
                . "define('DB_PASS', " . $x($cfg['pass']) . ");\n"
                . "define('APP_TIMEZONE', 'Asia/Karachi');\n";
            if (file_put_contents(APP_ROOT . '/includes/config.php', $config) === false) {
                throw new RuntimeException('Could not write includes/config.php — make the includes folder writable (755) and try again.');
            }
            @chmod(APP_ROOT . '/includes/config.php', 0640);
            // Try to remove the installer for safety
            @rename(__FILE__, APP_ROOT . '/data/install.php.done');
            $done = true;
        } catch (Throwable $t) {
            if (isset($pdo) && $pdo->inTransaction()) $pdo->rollBack();
            if (!empty($cfg['path']) && is_file(APP_ROOT . '/' . $cfg['path'])) @unlink(APP_ROOT . '/' . $cfg['path']);
            $errors[] = $t->getMessage();
        }
    }
}
